-- Service fields. Duplicate or blank existing serial numbers must be resolved
-- before applying this migration; no service records are deleted here.
lock table public.services_base in access exclusive mode;

do $$
begin
  if exists (
    select 1 from public.services_base
    where "serialNo" is null or btrim("serialNo") = ''
  ) or exists (
    select 1 from public.services_base group by "serialNo" having count(*) > 1
  ) then
    raise exception 'Service serial numbers must be nonempty and unique before migration';
  end if;
end;
$$;

create sequence public.services_serial_no_seq;
select pg_catalog.setval(
  'public.services_serial_no_seq',
  coalesce((select max(substring("serialNo" from '^SN-([0-9]+)-[0-9]{4}$')::bigint)
            from public.services_base), 0) + 1,
  false
);

alter table public.services_base
  alter column "serialNo" set not null,
  alter column "serialNo" set default (
    'SN-' || nextval('public.services_serial_no_seq')::text || '-' ||
    to_char(current_date, 'YYYY')
  ),
  alter column "serviceNo" drop not null,
  alter column area drop not null,
  alter column "modelNumber" drop not null,
  add column "technicianId2" uuid references public.employees_base (id),
  add column "technicianName2" text not null default '',
  add column notes text,
  add constraint services_base_distinct_technicians
    check ("technicianId" is null or "technicianId2" is null or "technicianId" <> "technicianId2");

create unique index services_base_serialno_unique_idx on public.services_base ("serialNo");

alter table public.services_base drop constraint services_base_status_check;
alter table public.services_base add constraint services_base_status_check
  check (status in ('open', 'in-progress', 'completed', 'cancelled', 'urgent'));

-- Existing view columns and their permissions remain unchanged. Appended aliases
-- expose the original technician assignment as Technician 1.
create or replace view public.services as
  select
    id, "serialNo", "serviceNo", "complaintDate", "customerId", "customerName", mobile, area,
    "townVillage", "invoiceNumber", "invoiceDate", "modelNumber", "complaintType", "attendedDate",
    "technicianId", "technicianName", status,
    "technicianId" as "technicianId1", "technicianName" as "technicianName1",
    "technicianId2", "technicianName2", notes
  from public.services_base
  where public.staff_role(auth.uid()) in ('admin', 'service')
    and "deletedAt" is null;

create or replace function public.services_view_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row public.services_base;
begin
  if public.staff_role(auth.uid()) is null or public.staff_role(auth.uid()) not in ('admin', 'service') then
    raise exception 'not authorized to add a service request';
  end if;
  if new."serialNo" is not null then
    raise exception 'serial number is generated by the database';
  end if;

  insert into public.services_base
    (id, "serviceNo", "complaintDate", "customerId", "customerName", mobile, area,
     "townVillage", "invoiceNumber", "invoiceDate", "modelNumber", "complaintType", "attendedDate",
     "technicianId", "technicianName", "technicianId2", "technicianName2", status, notes)
  values (
    coalesce(new.id, pg_catalog.gen_random_uuid()), nullif(new."serviceNo", ''),
    new."complaintDate", new."customerId", coalesce(new."customerName", ''), coalesce(new.mobile, ''),
    new.area, coalesce(new."townVillage", ''), coalesce(new."invoiceNumber", ''),
    new."invoiceDate", new."modelNumber", new."complaintType", new."attendedDate",
    coalesce(new."technicianId1", new."technicianId"),
    coalesce(new."technicianName1", new."technicianName", ''),
    new."technicianId2", coalesce(new."technicianName2", ''), coalesce(new.status, 'open'), new.notes
  ) returning * into v_row;

  new.id := v_row.id;
  new."serialNo" := v_row."serialNo";
  new."serviceNo" := v_row."serviceNo";
  new."customerName" := v_row."customerName";
  new.mobile := v_row.mobile;
  new."townVillage" := v_row."townVillage";
  new."invoiceNumber" := v_row."invoiceNumber";
  new."technicianId" := v_row."technicianId";
  new."technicianName" := v_row."technicianName";
  new."technicianId1" := v_row."technicianId";
  new."technicianName1" := v_row."technicianName";
  new."technicianName2" := v_row."technicianName2";
  new.status := v_row.status;
  return new;
end;
$$;

create or replace function public.services_view_update()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if public.staff_role(auth.uid()) is null or public.staff_role(auth.uid()) not in ('admin', 'service') then
    raise exception 'not authorized to update this service request';
  end if;
  if new."serialNo" is distinct from old."serialNo" then
    raise exception 'serial number cannot be changed';
  end if;

  update public.services_base set
    "serviceNo" = nullif(new."serviceNo", ''),
    "complaintDate" = new."complaintDate",
    "customerId" = new."customerId",
    "customerName" = new."customerName",
    mobile = new.mobile,
    area = new.area,
    "townVillage" = new."townVillage",
    "invoiceNumber" = new."invoiceNumber",
    "invoiceDate" = new."invoiceDate",
    "modelNumber" = new."modelNumber",
    "complaintType" = new."complaintType",
    "attendedDate" = new."attendedDate",
    "technicianId" = new."technicianId1",
    "technicianName" = coalesce(new."technicianName1", ''),
    "technicianId2" = new."technicianId2",
    "technicianName2" = coalesce(new."technicianName2", ''),
    status = new.status,
    notes = new.notes
  where id = old.id and "deletedAt" is null;

  new."technicianId" := new."technicianId1";
  new."technicianName" := new."technicianName1";
  return new;
end;
$$;

